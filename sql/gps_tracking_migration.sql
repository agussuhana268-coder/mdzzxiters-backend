-- NEXUS GPS tracking schema. Run once in Supabase SQL Editor.
-- Location data is only accepted while the device has an active, explicit consent
-- and an active tracking session. Backend uses the Supabase service role key.

create table if not exists public.gps_consents (
  id uuid primary key default gen_random_uuid(),
  license_key text not null,
  device_id text not null,
  consent_status text not null check (consent_status in ('GRANTED','REVOKED')),
  consented_at timestamptz,
  revoked_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (license_key, device_id)
);

create table if not exists public.gps_commands (
  id uuid primary key default gen_random_uuid(),
  command_id text not null unique,
  license_key text not null,
  device_id text not null,
  command text not null check (command in ('START_TRACKING','STOP_TRACKING')),
  status text not null default 'PENDING'
    check (status in ('PENDING','ACKNOWLEDGED','REJECTED','COMPLETED','FAILED')),
  requested_by text,
  created_at timestamptz not null default now(),
  acknowledged_at timestamptz
);

create table if not exists public.gps_tracking_sessions (
  id uuid primary key default gen_random_uuid(),
  tracking_session_id text not null unique,
  license_key text not null,
  device_id text not null,
  status text not null default 'ACTIVE' check (status in ('ACTIVE','STOPPED')),
  started_at timestamptz not null default now(),
  stopped_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.gps_locations (
  id bigint generated by default as identity primary key,
  license_key text not null,
  device_id text not null,
  nexus_id text,
  tracking_session_id text not null,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy double precision,
  altitude double precision,
  provider text,
  device_model text,
  recorded_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists gps_commands_device_status_idx
  on public.gps_commands (license_key, device_id, status, created_at);
create index if not exists gps_sessions_device_status_idx
  on public.gps_tracking_sessions (license_key, device_id, status);
create index if not exists gps_locations_device_recorded_idx
  on public.gps_locations (license_key, device_id, recorded_at desc);

alter table public.gps_consents enable row level security;
alter table public.gps_commands enable row level security;
alter table public.gps_tracking_sessions enable row level security;
alter table public.gps_locations enable row level security;

revoke all on public.gps_consents, public.gps_commands, public.gps_tracking_sessions, public.gps_locations from anon, authenticated;
grant all on public.gps_consents, public.gps_commands, public.gps_tracking_sessions, public.gps_locations to service_role;
grant usage, select on all sequences in schema public to service_role;
